// Korean / English nameplates for the report mastheads (site/brand/nameplates/*.svg + index.json),
// the same output as scripts/nameplates.ts but set from one OTF (Noto Sans KR Black, SIL OFL 1.1, which also
// holds Latin) instead of the Noto Sans SC woff slices. Run from the repo root:
//   node l10n/tools/nameplates.ts <ko|en-US> <NotoSansKR-Black.otf>
// It writes into l10n/<lang>/site/brand/nameplates/; l10n/apply.sh copies them into site/brand/nameplates/.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import opentype from "opentype.js";

const [lang, fontFile] = process.argv.slice(2);
if (!lang || !fontFile) throw new Error("usage: node l10n/tools/nameplates.ts <ko|en-US> <NotoSansKR-Black.otf>");

const S = "AI";
const SETS: Record<string, Record<string, Array<{ text: string; accent: boolean }>>> = {
  ko: {
    daily: [{ text: S, accent: true }, { text: "일간", accent: false }],
    weekly: [{ text: S, accent: true }, { text: "주간", accent: false }],
    monthly: [{ text: S, accent: true }, { text: "월간", accent: false }],
    archive: [{ text: "브리핑", accent: false }, { text: "모음", accent: true }],
  },
  "en-US": {
    daily: [{ text: S, accent: true }, { text: "Daily", accent: false }],
    weekly: [{ text: S, accent: true }, { text: "Weekly", accent: false }],
    monthly: [{ text: S, accent: true }, { text: "Monthly", accent: false }],
    archive: [{ text: "The", accent: false }, { text: "Archive", accent: true }],
  },
};
const NAMEPLATES = SETS[lang];
if (!NAMEPLATES) throw new Error(`unknown language ${lang}`);

const H = 220;
const CAPS = H * 0.94;
const MARGIN = 12;
const isLatin = (ch: string) => /[A-Za-z]/.test(ch);
/** Space between the inks of two neighbouring parts (words), and between two Hangul syllables. */
const PART_GAP = H * 0.17;
const SYLLABLE_GAP = H * 0.085;

const buf = readFileSync(fontFile);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
// Latin words are set as words (the font's own spacing and kerning); Hangul syllable by syllable, like the original.
const units = (text: string) => ([...text].every(isLatin) ? [text] : [...text]);
const all = [...new Set(Object.values(NAMEPLATES).flatMap((parts) => parts.flatMap((p) => units(p.text))))];
const boxes = new Map([...all, "H"].map((u) => [u, font.getPath(u, 0, 0, 1000).getBoundingBox()]));
function fit(group: string[], height: number) {
  const top = Math.min(...group.map((u) => boxes.get(u)!.y1));
  const bottom = Math.max(...group.map((u) => boxes.get(u)!.y2));
  const size = (1000 * height) / (bottom - top);
  return { size, baseline: -((top + bottom) / 2) * (size / 1000) };
}
// Capitals (cap height) decide the Latin scale, so "AI" and "Daily" share one cap height.
const latin = fit(["H"], CAPS * 0.86);
const hangulUnits = all.filter((u) => !isLatin(u));
const hangul = hangulUnits.length ? fit(hangulUnits, H) : latin;

const out: Record<string, { viewBox: string; accent: string; ink: string }> = {};
for (const [name, parts] of Object.entries(NAMEPLATES)) {
  const accent: string[] = [];
  const ink: string[] = [];
  let x = MARGIN;
  let started = false;
  for (const part of parts) {
    let first = true;
    for (const u of units(part.text)) {
      const { size, baseline } = isLatin(u) ? latin : hangul;
      const box = boxes.get(u)!;
      const scale = size / 1000;
      if (started) x += first ? (isLatin(u) ? PART_GAP * 1.4 : PART_GAP) : SYLLABLE_GAP;
      const origin = x - box.x1 * scale;
      (part.accent ? accent : ink).push(font.getPath(u, origin, baseline, size).toPathData(1));
      x = origin + box.x2 * scale;
      started = true;
      first = false;
    }
  }
  const half = Math.max(H, CAPS) / 2 + MARGIN;
  out[name] = { viewBox: `0 ${(-half).toFixed(1)} ${(x + MARGIN).toFixed(1)} ${(2 * half).toFixed(1)}`, accent: accent.join(" "), ink: ink.join(" ") };
}

const target = `l10n/${lang}/site/brand/nameplates`;
mkdirSync(target, { recursive: true });
for (const [name, n] of Object.entries(out)) {
  writeFileSync(`${target}/${name}.svg`, `<!-- Generated by l10n/tools/nameplates.ts. Noto Sans KR Black (SIL OFL 1.1). -->\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="${n.viewBox}"><path id="accent" d="${n.accent}"/><path id="ink" d="${n.ink}"/></svg>\n`);
}
writeFileSync(`${target}/index.json`, `${JSON.stringify(Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.viewBox])), null, 2)}\n`);
